        "    \"\"\"Select the model's columns, convert to numbers, treat inf/huge values as missing.\"\"\"\n",
        "    missing = [c for c in cols if c not in df.columns]\n",
        "    if missing:\n",
        "        return None, missing\n",
        "    X = df[cols].apply(pd.to_numeric, errors=\"coerce\").astype(\"float64\")\n",
